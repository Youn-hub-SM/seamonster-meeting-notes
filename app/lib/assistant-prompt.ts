export async function setAssistantPrompt(text: string, by?: string): Promise<void> {
  const t = (text || "").trim();
  await setKv(KEY, t === DEFAULT_ASSISTANT_PROMPT.trim() ? "" : t);
  try { await setKv(META, JSON.stringify({ by: by || "", at: new Date().toISOString() })); } catch { /* 기록 실패는 무시 */ }
}
