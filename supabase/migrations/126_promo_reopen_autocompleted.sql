-- 126 프로모션 요청서 다시 열기 — '마감 = 소매 합류' 전환(2026-10-06 대표 결정)
--
-- ■ 왜
--   예전 규칙은 배정이 100% 가 되면 프로모션 요청서를 자동 '완료'로 닫았고, 확보분은 행사 하루 전 아침 크론이 소매로 돌렸다.
--   크론을 없애고 사람이 '마감'을 누를 때 합류하도록 바꾸면서, 행사가 아직 오지 않은 '완료' 요청서는
--   ① 행에 '마감' 버튼이 없어 확보분을 소매로 돌릴 길이 없고 ② 다른 요청서를 마감할 때 그 몫이 보호되지 않는다.
--   그래서 그런 요청서를 '진행중'으로 다시 연다(새 규칙에서 프로모션 요청서는 마감 전까지 열려 있다).
--
-- ■ 대상
--   용도 프로모션 · 상태 완료 · 목표일(행사 시작일)이 오늘(KST) 이후이거나 비어 있는 것.
--   예전엔 사람이 '마감'해도 확보분이 크론 전까지 프로모션 칸에 남아 있었으므로 그런 요청서도 다시 여는 게 맞다.
--
-- 적용: 운영 배포 직후 Supabase Dashboard > SQL Editor 에 붙여넣고 Run. **한 번만** 실행(새 규칙의 '마감'은 합류까지 끝내므로
--   나중에 다시 돌리면 이미 합류한 요청서가 다시 열린다 — 해는 없지만 헷갈린다).

update public.production_requests
   set status = '진행중', updated_at = now()
 where purpose = '프로모션'
   and status = '완료'
   and (due_date is null or due_date >= (now() at time zone 'Asia/Seoul')::date);
