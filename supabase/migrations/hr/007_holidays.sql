-- ■ 무엇을 하나
--   · hr.holidays — 쉬는 날(유급 휴일) 목록. 날짜 하나에 한 줄. [요율] 화면 아래 '공휴일'에서 보고, 더하고, 지운다.
--   · 근무대장의 [평소대로 채우기]가 이 목록의 날을 '근무' 대신 '유급 휴일'로 채운다(소정근로일일 때만).
--       상시 5인 이상 사업장: 목록의 모든 날. 5인 미만 사업장: 노동절(5월 1일)만 — 관공서 공휴일의 유급 의무가 5인 이상에만 있다.
--   · 연차 [사용 등록]은 이 목록의 날에 연차를 넣지 않는다(공휴일에 연차가 깎이지 않게).
--   이 표가 근무·급여 계산을 직접 바꾸지는 않는다 — 근무대장에 '유급 휴일' 줄이 저장돼야 급여에 들어간다(지금까지와 같다).
-- ■ 처음 값(2026·2027년)
--   대체공휴일·선거일까지 넣어 둔다. 날짜는 공개 달력 두 곳(2차 자료)을 대조한 것이다 — **관보·정부 달력과 한 번 확인할 것.**
--   특히 ① 노동절(5/1)과 제헌절(7/17)이 2026년부터 공휴일이라는 것 ② 2026-06-03 지방선거일 ③ 2027년 설날(2/7)과 대체공휴일.
--   틀린 날은 화면에서 지우고, 임시공휴일·회사 휴일은 화면에서 더한다.
--   2028년부터는 넣지 않았다(설날 날짜가 자료마다 달랐다) — 화면의 [정해진 공휴일 넣기]로 날짜가 고정된 날을 넣고, 설·추석·부처님 오신 날·대체공휴일은 직접 더한다.
-- ■ 미적용이면
--   공휴일 구역이 'DB 준비 전(hr/007 적용)'을 보이고, [평소대로 채우기]는 지금처럼 모든 소정근로일을 '근무'로 채운다.
